#!/usr/bin/env python3
"""Turn Commander Spellbook "find my combos" results into src/rules/combosSpellbook.ts.

Input: a JSON file {deckId: [variant, ...]}: for each deck, the "included" variants that
POST https://backend.commanderspellbook.com/find-my-combos returns for its list (the copy for
Zach's decks is /mnt/project-files/proliferate/spellbook-combos.json). The cloud container can't
reach Spellbook; the lookup was run from a browser on the backend's own origin. Only combos that end the game, or give infinite mana for a finisher to
spend, are kept. Usage: python3 scripts/spellbook-combos.py spellbook-combos.json
"""
import json, re, sys

R = json.load(open(sys.argv[1]))
variants = {v['id']: v for vs in R.values() for v in vs}

# Already written by hand in wincons.ts.
HAND_WRITTEN = {'4821-5261', '936-1290'}
# Prerequisites the engine can't check (a way to kill a creature, an unblockable attack, an
# indestructible Bruvac, max speed, a creature that attacked this turn): left out.
UNCHECKABLE = {'1154-2144-3729', '1758-2144-3729', '2144-3560-3729', '263-2144-3729', '1263-2034-4871', '1800-2429', '2751-3557', '95-6746', '4659-5078-6263'}
# Mana the "notable prerequisites" ask for from lands, when the loop lists none.
LAND_MANA = {'112-565-3821': 5, '565-2450-3821': 4, '565-2909-3821': 4, '1987-2493-3821': 3, '1741-1770-1987-2493': 2, '1741-1987-2397-2493': 2, '147-802': 5}
LIFE = {'Sanguine Bond', 'Vito, Thorn of the Dusk Rose', 'Exquisite Blood', 'Bloodthirsty Conqueror'}

ORDER = ['win', 'drain', 'mill', 'one', 'millOne', 'mana', 'draw']
def kind_of(features):
    kinds = set()
    for f in features:
        if f.startswith('Win the game') or f.startswith('Infinite turns') or f in ('Infinite creature tokens',):
            kinds.add('win')
        elif f in ('Infinite damage', 'Infinite lifeloss', 'Near-infinite lifeloss'):
            kinds.add('drain')
        elif f == 'Infinite mill':
            kinds.add('mill')
        elif f in ('Near-infinite lifeloss for target opponent', 'Target opponent loses the game', 'Infinite damage to one opponent'):
            kinds.add('one')
        elif f == 'Infinite mill for target opponent':
            kinds.add('millOne')
        elif f in ('Infinite colorless mana', 'Infinite colored mana', 'Near-infinite colorless mana') or f.startswith('Infinite mana'):
            kinds.add('mana')
        elif f in ('Infinite card draw', 'Near-infinite card draw'):
            kinds.add('draw')
    for k in ORDER:
        if k in kinds:
            return k
    return None

def template(name):
    if name == 'Persist Creature': return 'persist'
    if name == 'Extra Turn Spell': return 'extraTurn'
    m = re.match(r'Permanent Castable for ((?:\{C\})+)$', name)
    if m: return 'cheapPermanent:%d' % (len(m.group(1)) // 3)
    if name.startswith('Artifact Castable for {0}'): return 'zeroArtifact'
    if 'Mana Rock' in name: return 'manaRock'
    return None

def mana_of(s):
    s = s or ''
    head = s.split(' ')[0] if s.startswith('{') else ''
    total = 0
    for sym in re.findall(r'\{([^}]+)\}', head):
        total += int(sym) if sym.isdigit() else 1
    return total

out = []
for v in sorted(variants.values(), key=lambda v: v['id']):
    if v['id'] in HAND_WRITTEN or v['id'] in UNCHECKABLE: continue
    names = [u[0] for u in v['u']]
    if len(names) == 2 and set(names) <= LIFE: continue
    kind = kind_of(v['p'])
    if not kind: continue
    needs = []
    ok = True
    for r in v['rq']:
        t = template(r[0])
        if not t: ok = False
        needs.append(t)
    if not ok: continue
    pieces = []
    for name, zones, cmdr, bstate, estate, gstate, lstate in v['u']:
        piece = {'n': name, 'z': zones}
        if 'summoning sickness' in bstate: piece['ready'] = True
        if 'Isochron Scepter' in estate: piece['z'] = 'S'
        pieces.append(piece)
    entry = {'id': v['id'], 'name': ' + '.join(names), 'kind': kind, 'pieces': pieces}
    m = mana_of(v['m']) or LAND_MANA.get(v['id'], 0)
    if m: entry['mana'] = m
    if needs: entry['needs'] = needs
    out.append(entry)

lines = [
    '// Generated by scripts/spellbook-combos.py from Commander Spellbook (commanderspellbook.com)',
    '// "find my combos" results for the decks in the project. Do not edit by hand.',
    '//',
    '// Zones: B battlefield, H hand, G graveyard, E exile, C command zone, L library, S imprinted on',
    '// Isochron Scepter; several letters mean any of them. `ready`: a creature that has been under',
    '// its controller\'s control since the turn began. `mana`: mana the loop needs on top of the pieces.',
    '',
    "import type { SpellbookCombo } from './wincons';",
    '',
    'export const SPELLBOOK_COMBOS: SpellbookCombo[] = [',
]
for e in out:
    lines.append('  ' + json.dumps(e, ensure_ascii=False) + ',')
lines.append('];')
lines.append('')
open('src/rules/combosSpellbook.ts', 'w').write('\n'.join(lines))
print(len(out), 'combos written')
